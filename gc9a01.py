# MADCTL values for rotation 0/90/180/270 (BGR bit set)
_MADCTL = {0: 0x08, 90: 0x68, 180: 0xC8, 270: 0xA8}


class GC9A01:
    def __init__(self, dc=25, rst=27, bl=18, spi_bus=0, spi_dev=0,
                 speed_hz=40_000_000, rotation=0):
        self.dc = DigitalOutputDevice(dc)
        self.rst = DigitalOutputDevice(rst)
        self.bl = PWMLED(bl)
        self.spi = spidev.SpiDev()
        self.spi.open(spi_bus, spi_dev)
        self.spi.max_speed_hz = speed_hz
        self.spi.mode = 0
        self._reset()
        for cmd, data, delay in _INIT:
            self._cmd(cmd, data)
            if delay:
                time.sleep(delay / 1000)
        self._cmd(0x36, [_MADCTL[rotation]])
        self.brightness(1.0)

    def _reset(self):
        self.rst.on(); time.sleep(0.01)
        self.rst.off(); time.sleep(0.01)
        self.rst.on(); time.sleep(0.12)

    def _cmd(self, cmd, data=()):
        self.dc.off()
        self.spi.writebytes([cmd])
        if data:
            self.dc.on()
            self.spi.writebytes(list(data))

    def brightness(self, level):
        self.bl.value = max(0.0, min(1.0, level))

    def show(self, image):
        """Push a 240x240 PIL RGB image to the screen."""
        a = np.asarray(image.convert("RGB"), dtype=np.uint16)
        rgb565 = ((a[..., 0] & 0xF8) << 8) | ((a[..., 1] & 0xFC) << 3) | (a[..., 2] >> 3)
        buf = rgb565.astype(">u2").tobytes()
        self._cmd(0x2A, [0, 0, 0, WIDTH - 1])
        self._cmd(0x2B, [0, 0, 0, HEIGHT - 1])
        self._cmd(0x2C)
        self.dc.on()
        self.spi.writebytes2(buf)

    def close(self):
        self.brightness(0)
        self.spi.close()
